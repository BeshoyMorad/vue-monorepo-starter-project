import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const localesDir = fileURLToPath(new URL('../locales/', import.meta.url));
const locales = [
  { code: 'en', common: 'commonEn' },
  { code: 'ar', common: 'commonAr' },
] as const;

/**
 * Builds the `en.ts` and `ar.ts` loaders from the namespace files in `locales/{locale}/`.
 * `types/i18n.d.ts` derives the message types from `WebsiteLocaleSchema` in `en.ts`,
 * so new files are typed automatically.
 */
export function generateLocaleTypes(): boolean {
  let changed = false;

  for (const { code, common } of locales) {
    const dir = `${localesDir}${code}`;
    const namespaces = (existsSync(dir) ? readdirSync(dir) : [])
      .filter((file) => file.endsWith('.json'))
      .map((file) => file.slice(0, -'.json'.length))
      .sort();
    const messages = `website${code === 'en' ? 'En' : 'Ar'}`;

    const content = [
      `// Generated by scripts/generate-locale-types.ts from locales/${code}/*.json. Do not edit.`,
      `import { ${common}, mergeLocaleMessages } from '@workspace/locales';`,
      ...namespaces.map((name) => `import ${name} from './${code}/${name}.json';`),
      '',
      `export const ${messages} = {`,
      ...namespaces.map((name) => `  ${name},`),
      '};',
      '',
      ...(code === 'en' ? [`export type WebsiteLocaleSchema = typeof ${messages};`, ''] : []),
      'export default defineI18nLocale(async () => {',
      `  return mergeLocaleMessages(${common}, ${messages});`,
      '});',
      '',
    ].join('\n');

    const outFile = `${localesDir}${code}.ts`;
    let current = '';
    try {
      current = readFileSync(outFile, 'utf8');
    } catch {
      // First run: the file does not exist yet.
    }
    if (current !== content) {
      writeFileSync(outFile, content);
      changed = true;
    }
  }

  return changed;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateLocaleTypes();
}
