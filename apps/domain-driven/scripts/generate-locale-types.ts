import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const localesDir = fileURLToPath(new URL('../src/locales/', import.meta.url));
const outFile = `${localesDir}messages.generated.ts`;

/** Builds `messages.generated.ts` from every `src/locales/en/*.json` file. */
export function generateLocaleTypes(): boolean {
  // The folder is optional: an app without its own namespaces just uses the shared messages.
  const files = existsSync(`${localesDir}en`) ? readdirSync(`${localesDir}en`) : [];
  const namespaces = files
    .filter((file) => file.endsWith('.json'))
    .map((file) => file.slice(0, -'.json'.length))
    .sort();

  const content = [
    '// Generated by scripts/generate-locale-types.ts from src/locales/en/*.json (plus the shared common messages). Do not edit.',
    "import type { CommonLocaleSchema } from '@workspace/locales';",
    ...namespaces.map((name) => `import type ${name} from './en/${name}.json';`),
    '',
    ...(namespaces.length
      ? [
          'export interface MessageSchema extends CommonLocaleSchema {',
          ...namespaces.map((name) => `  ${name}: typeof ${name};`),
          '}',
        ]
      : ['export type MessageSchema = CommonLocaleSchema;']),
    '',
  ].join('\n');

  let current = '';
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {
    // First run: the file does not exist yet.
  }
  if (current === content) return false;

  writeFileSync(outFile, content);
  return true;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateLocaleTypes();
}
